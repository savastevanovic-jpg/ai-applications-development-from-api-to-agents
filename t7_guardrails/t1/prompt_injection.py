def main():
    #TODO 1:
    # 1. Create Anthropic client, model to use `haiku` (Anthropic's smallest/fastest model)
    llm_client = Anthropic(api_key=ANTHROPIC_API_KEY)
    # 2. Create messages array with user message with PROFILE info as first message (system prompt is passed
    #    separately in Anthropic's API, we emulate the flow when we retrieved PII from some DB and put it as
    #    user message).
    messages = [{"role": "user", "content": PROFILE}]
    # 3. Create console chat with LLM, preserve history (user and assistant messages should be added to messages array
    #   and each new request you must provide whole conversation history. With preserved history we can make multistep
    #   (more complicated strategy) of prompt injection).
    while True:
        user_input = input("User: ")
        if user_input.lower() in ["exit", "quit"]:
            print("Exiting chat.")
            break
        messages.append({"role": "user", "content": user_input})
        response = llm_client.messages.create(
            model='claude-haiku-4-5',
            max_tokens=1024,
            temperature=0.0,
            system=SYSTEM_PROMPT,
            messages=messages
        )
        assistant_response = " ".join([block.text for block in response.content])
        print(f"Assistant: {assistant_response}")
        messages.append({"role": "assistant", "content": assistant_response})

main()

